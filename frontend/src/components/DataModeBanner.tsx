import { useQuery } from '@tanstack/react-query'

import { api } from '@/lib/api'

/**
 * A standing, unmissable statement of where the numbers come from. It appears
 * whenever the server is not serving live provider data — the product must
 * never let a demo dataset pass for a measurement.
 */
export function DataModeBanner() {
  const { data } = useQuery({ queryKey: ['status'], queryFn: api.status,
    staleTime: 60_000, retry: 1 })
  if (!data) return null

  const demo = data.data_mode === 'demo'
  const missingProviders = !data.capabilities.air_quality_provider
    || !data.capabilities.weather_provider

  if (!demo && !missingProviders) return null

  return (
    <div role="status"
         className="border-b border-usg/30 bg-usg/10 px-4 py-2 text-center text-xs
                    text-ink sm:px-6">
      <span className="font-semibold text-usg">
        {demo ? 'DEMO DATA' : 'LIMITED DATA'}
      </span>
      <span className="ml-2 text-muted">
        {demo
          ? 'Readings are generated by the AIRS physical model, not measured. '
            + 'Set AIRS_DATA_MODE=live with provider keys for real data.'
          : 'One or more upstream providers are not configured, so parts of the '
            + 'platform are running on modelled data.'}
      </span>
    </div>
  )
}
