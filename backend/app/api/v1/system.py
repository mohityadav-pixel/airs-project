from __future__ import annotations

from datetime import datetime, timezone

from fastapi import APIRouter, Depends
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.ai import gemini
from app.core.config import settings
from app.db.models import AirQualityReading, Provenance
from app.db.session import get_db
from app.domain.aqi import categories_payload
from ml.model import read_manifest

router = APIRouter(prefix="/system", tags=["system"])


@router.get("/status")
def status(db: Session = Depends(get_db)) -> dict:
    """What is actually working right now — the UI uses this to render its
    LIVE / DEMO badge and to hide features that are not configured."""
    counts = dict(db.execute(
        select(AirQualityReading.provenance, func.count())
        .group_by(AirQualityReading.provenance)).all())
    live_rows = counts.get(Provenance.live, 0)
    demo_rows = counts.get(Provenance.demo, 0)
    manifest = read_manifest()

    return {
        "service": "AIRS",
        "environment": settings.airs_env,
        "data_mode": settings.airs_data_mode,
        "capabilities": {
            **settings.capability_report(),
            "ai_copilot": gemini.available(),
            "ml_models_trained": bool(manifest),
        },
        "data": {
            "live_readings": live_rows,
            "demo_readings": demo_rows,
            "total_readings": live_rows + demo_rows,
            "note": ("Rows marked demo are generated by the AIRS physical model "
                     "and are labelled as such everywhere they appear."),
        },
        "model": {
            "trained_at": (manifest or {}).get("trained_at"),
            "model_name": (manifest or {}).get("model_name"),
            "model_version": (manifest or {}).get("model_version"),
            "reports": (manifest or {}).get("reports", []),
        },
        "server_time": datetime.now(timezone.utc),
    }


@router.get("/aqi-scale")
def aqi_scale(scale: str = "us_epa") -> dict:
    return {"scale": scale, "categories": categories_payload(scale)}  # type: ignore[arg-type]


@router.get("/health")
def health() -> dict:
    return {"status": "ok"}
