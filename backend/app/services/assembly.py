"""Assembles API-shaped payloads from stored rows.

Routers stay thin; this module owns the mapping from database entities to the
response schemas, including the provenance stamp that every payload carries.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone

from sqlalchemy.orm import Session

from app.core.config import settings
from app.db.models import AirQualityReading, City, Provenance, Station
from app.domain.aqi import (POLLUTANT_LABELS, POLLUTANT_UNITS_US, categories_payload,
                             categorize, concentration_to_index, trend_of)
from app.schemas.air import (CategoryOut, CityOut, CurrentAirQuality, PollutantOut,
                              StationOut, TrafficOut, TrendOut, WeatherOut)
from app.schemas.common import DataKind, DataProvenance, SourceMode
from app.services import repository
from app.services.validation import is_stale

POLLUTANT_KEYS = ("pm25", "pm10", "no2", "so2", "co", "o3")


def city_out(city: City, station_count: int | None = None) -> CityOut:
    return CityOut(id=city.id, slug=city.slug, name=city.name, country=city.country,
                   latitude=city.latitude, longitude=city.longitude,
                   population=city.population, default_zoom=city.default_zoom,
                   aqi_scale=city.aqi_scale,
                   station_count=station_count if station_count is not None
                   else len(city.stations))


def station_out(station: Station) -> StationOut:
    return StationOut(id=station.id, code=station.code, name=station.name,
                      latitude=station.latitude, longitude=station.longitude,
                      zone_type=station.zone_type.value,
                      population_exposed=station.population_exposed,
                      near_major_road=station.near_major_road,
                      near_industrial=station.near_industrial,
                      near_construction=station.near_construction)


def category_out(aqi: float | None) -> CategoryOut | None:
    cat = categorize(aqi)
    if cat is None:
        return None
    return CategoryOut(key=cat.key, label=cat.label, color=cat.color,
                       advice=cat.short_advice)


def provenance_for(reading, kind: DataKind = DataKind.observed,
                   source: str | None = None) -> DataProvenance:
    if reading is None:
        return DataProvenance(kind=kind, mode=SourceMode(settings.airs_data_mode
                                                          if settings.airs_data_mode != "auto"
                                                          else "live"),
                              source=source or "AIRS", is_stale=True)
    mode = (SourceMode.demo if getattr(reading, "provenance", None) == Provenance.demo
            else SourceMode.live)
    observed_at = getattr(reading, "observed_at", None)
    flags = getattr(reading, "quality_flags", None) or []
    modelled = mode == SourceMode.live and "source:cams" in flags
    if modelled and kind == DataKind.observed:
        kind = DataKind.estimated
    default_source = ("AIRS synthetic model" if mode == SourceMode.demo
                      else "CAMS model (Open-Meteo)" if modelled
                      else "WAQI / AQICN monitoring station")
    return DataProvenance(
        kind=kind, mode=mode,
        source=source or default_source,
        observed_at=observed_at,
        generated_at=datetime.now(timezone.utc),
        is_stale=is_stale(observed_at),
        note=("Synthetic data generated by the AIRS physical model. Not a real "
              "measurement." if mode == SourceMode.demo
              else "No monitoring station is close enough, so this value comes "
                   "from the CAMS atmospheric model." if modelled else None))


def pollutants_from(reading: AirQualityReading) -> list[PollutantOut]:
    subs = reading.sub_indices or {}
    out: list[PollutantOut] = []
    overall = reading.aqi or 0
    for key in POLLUTANT_KEYS:
        value = getattr(reading, key, None)
        sub = subs.get(key)
        if sub is None and value is not None:
            sub = concentration_to_index(key, value)
        if value is None and sub is None:
            continue
        share = round(sub / overall * 100, 1) if (sub and overall) else None
        out.append(PollutantOut(
            key=key, label=POLLUTANT_LABELS[key], concentration=value,
            unit=POLLUTANT_UNITS_US[key], sub_index=sub, share_of_aqi=share,
            category=category_out(sub)))
    out.sort(key=lambda p: p.sub_index or 0, reverse=True)
    return out


def current_air_quality(db: Session, city: City, station: Station) -> CurrentAirQuality:
    reading = repository.latest_air_quality(db, station.id)
    weather = repository.latest_weather(db, station.id)
    traffic = repository.latest_traffic(db, station.id)
    series = repository.air_quality_series(db, station.id, hours=26)

    prev_1h = series[-2] if len(series) >= 2 else None
    # Compare with the reading nearest to exactly 24 h ago — not simply the
    # oldest row in the window, which is the same row as "now" when only one
    # snapshot has been stored and so always reported "0% better".
    prev_24h = None
    if reading is not None:
        target = reading.observed_at - timedelta(hours=24)
        candidates = [r for r in series if r.aqi is not None
                      and abs((r.observed_at - target).total_seconds()) <= 3 * 3600]
        if candidates:
            prev_24h = min(candidates, key=lambda r: abs(
                (r.observed_at - target).total_seconds()))

    return CurrentAirQuality(
        station=station_out(station), city=city_out(city),
        observed_at=reading.observed_at if reading else None,
        aqi=reading.aqi if reading else None,
        category=category_out(reading.aqi) if reading else None,
        dominant_pollutant=reading.dominant_pollutant if reading else None,
        pollutants=pollutants_from(reading) if reading else [],
        trend_1h=TrendOut(**trend_of(reading.aqi if reading else None,
                                      prev_1h.aqi if prev_1h else None)),
        trend_24h=TrendOut(**trend_of(reading.aqi if reading else None,
                                       prev_24h.aqi if prev_24h else None)),
        weather=WeatherOut(
            observed_at=weather.observed_at, temperature_c=weather.temperature_c,
            humidity_pct=weather.humidity_pct, pressure_hpa=weather.pressure_hpa,
            wind_speed_mps=weather.wind_speed_mps, wind_deg=weather.wind_deg,
            rain_1h_mm=weather.rain_1h_mm, clouds_pct=weather.clouds_pct,
            visibility_m=weather.visibility_m, condition=weather.condition,
            ventilation_index=weather.ventilation_index) if weather else None,
        traffic=TrafficOut(
            observed_at=traffic.observed_at,
            congestion_index=traffic.congestion_index,
            speed_ratio=traffic.speed_ratio,
            vehicle_volume_est=traffic.vehicle_volume_est) if traffic else None,
        quality_flags=(reading.quality_flags or []) if reading else ["no_data"],
        provenance=provenance_for(reading))


def legend() -> list[CategoryOut]:
    return [CategoryOut(**c) for c in
            [{"key": c["key"], "label": c["label"], "color": c["color"],
              "advice": c["advice"]} for c in categories_payload("us_epa")]]
